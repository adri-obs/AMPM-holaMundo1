package practicas.practica4

class Calculadora {


    fun sumar(a: Int, b: Int): Int {
        return a + b
    }
    fun resta(a: Int, b: Int): Int {
        return a-b
    }
    fun multiplicacion(a: Int, b: Int): Int {
        return a*b
    }
    fun division(a: Int, b: Int): Int {
        return a/b
    }
}
